#!/usr/bin/env python3
"""Train the random forest the ml-detector module embeds and write everything
the Rust side needs to carry it.

    conda run -n wasmsentinel python3 train/train_rf.py

Outputs (paths relative to rules/ml-detector):
  train/rf_model.bin             forest byte image (WSRF v1, forest_export.py)
  train/rf_model.json            training facts: data, hyper-parameters, size, sha256
  src/forest_meta.rs             the same facts as Rust constants (model_info export)
  train/fixtures/forest_golden.json  sequences with scikit-learn probabilities for
                                 tests/forest_golden.rs and verify_wasm_parity.py

The forest is a scikit-learn RandomForestClassifier with the hyper-parameters
of the E1 "rf" baseline (300 trees, balanced class weights, unlimited depth)
trained on every ADFA-LD trace with feature set v1. Its cross-validated
accuracy is the E1 "wasmsentinel_rf" arm, which trains the same model per
fold and scores through the module.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import platform
import subprocess
import sys
import time
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from forest_export import forest_predict, forest_stats, forest_to_bytes  # noqa: E402
from train_mlp import extract_features, parse_syscall_trace  # noqa: E402
from verify_wasm_parity import synthetic_sequences  # noqa: E402


def load_traces(adfa_dir: Path):
    seqs, labels, paths = [], [], []
    for sub in ("Training_Data_Master", "Validation_Data_Master"):
        for f in sorted((adfa_dir / sub).glob("*.txt")):
            s = parse_syscall_trace(str(f))
            if s:
                seqs.append(s)
                labels.append(0)
                paths.append(str(f.relative_to(adfa_dir)))
    for d in sorted((adfa_dir / "Attack_Data_Master").iterdir()):
        if d.is_dir():
            for f in sorted(d.glob("*.txt")):
                s = parse_syscall_trace(str(f))
                if s:
                    seqs.append(s)
                    labels.append(1)
                    paths.append(str(f.relative_to(adfa_dir)))
    return seqs, np.asarray(labels), paths


def sh(cmd: str) -> str:
    try:
        return subprocess.check_output(cmd, shell=True, text=True, cwd=HERE).strip()
    except Exception:  # noqa: BLE001
        return ""


def rust_meta(meta: dict) -> str:
    return f'''//! Facts about the embedded random forest (train/{meta["source"]}).
//!
//! Generated by train/train_rf.py; do not edit. Regenerate with
//!   python3 train/train_rf.py
//!
//! {meta["n_trees"]} trees, {meta["n_nodes"]} nodes, max depth {meta["max_depth"]},
//! {meta["bytes"]} bytes; trained on {meta["training"]}.

/// Forest file this module embeds (relative to rules/ml-detector/train).
pub const RF_MODEL_SOURCE: &str = "{meta["source"]}";
/// SHA-256 of that file.
pub const RF_MODEL_SHA256: &str = "{meta["sha256"]}";
/// Number of trees.
pub const RF_N_TREES: usize = {meta["n_trees"]};
/// Number of nodes over all trees.
pub const RF_N_NODES: usize = {meta["n_nodes"]};
/// Deepest tree.
pub const RF_MAX_DEPTH: usize = {meta["max_depth"]};
/// Training data and learner, for `model_info`.
pub const RF_TRAINING: &str = "{meta["training"]}";
'''


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--adfa-dir", type=Path, default=HERE.parents[2] / "evaluation/datasets/raw/ADFA-LD/ADFA-LD")
    ap.add_argument("--trees", type=int, default=300)
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--out-bin", type=Path, default=HERE / "rf_model.bin")
    ap.add_argument("--out-json", type=Path, default=HERE / "rf_model.json")
    ap.add_argument("--out-meta", type=Path, default=HERE.parent / "src/forest_meta.rs")
    ap.add_argument("--fixture", type=Path, default=HERE / "fixtures/forest_golden.json")
    args = ap.parse_args()

    import sklearn
    from sklearn.ensemble import RandomForestClassifier

    t0 = time.time()
    seqs, y, paths = load_traces(args.adfa_dir)
    X = np.stack([extract_features(s) for s in seqs]).astype(np.float32)
    print(f"{len(seqs)} traces ({int((y == 0).sum())} normal, {int(y.sum())} attack), features {X.shape}")
    model = RandomForestClassifier(n_estimators=args.trees, class_weight="balanced", random_state=args.seed, n_jobs=-1)
    model.fit(X, y)
    blob = forest_to_bytes(model)
    stats = forest_stats(model, blob)
    print("forest:", json.dumps(stats))

    # The exporter is checked against scikit-learn on every training trace.
    ref = model.predict_proba(X)[:, 1]
    mine = forest_predict(blob, X)
    max_diff = float(np.max(np.abs(ref - mine)))
    print(f"exporter vs scikit-learn predict_proba: max |diff| {max_diff:.2e} over {len(X)} traces")
    if max_diff > 1e-6:
        print("exporter disagrees with scikit-learn", file=sys.stderr)
        return 1

    args.out_bin.write_bytes(blob)
    training = (f"ADFA-LD, {len(seqs)} traces ({int((y == 0).sum())} normal, {int(y.sum())} attack), feature set v1; "
                f"scikit-learn {sklearn.__version__} RandomForestClassifier(n_estimators={args.trees}, class_weight=balanced, random_state={args.seed})")
    meta = {
        "source": args.out_bin.name, "training": training, **stats,
        "exporter_vs_sklearn_max_abs_diff": max_diff,
        "git_commit": sh("git rev-parse HEAD"), "sklearn": sklearn.__version__, "numpy": np.__version__,
        "python": platform.python_version(), "timestamp": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "seconds": round(time.time() - t0, 1),
    }
    args.out_json.write_text(json.dumps(meta, indent=1) + "\n")
    args.out_meta.write_text(rust_meta(meta))

    # Golden fixture: synthetic sequences plus real traces from both classes,
    # scored by scikit-learn on the training-code features.
    rng = np.random.default_rng(args.seed)
    normal_idx = rng.choice(np.flatnonzero(y == 0), 8, replace=False)
    attack_idx = rng.choice(np.flatnonzero(y == 1), 8, replace=False)
    cases = []
    for s in synthetic_sequences(24)[::2]:
        cases.append({"syscalls": [int(v) for v in s], "source": "synthetic"})
    for i in list(normal_idx) + list(attack_idx):
        cases.append({"syscalls": [int(v) for v in seqs[i]], "source": paths[i]})
    F = np.stack([extract_features(c["syscalls"]) for c in cases]).astype(np.float32)
    probs = model.predict_proba(F)[:, 1]
    for c, p in zip(cases, probs):
        c["prob"] = float(p)
    args.fixture.parent.mkdir(parents=True, exist_ok=True)
    args.fixture.write_text(json.dumps({"forest": args.out_bin.name, "sha256": stats["sha256"], "cases": cases}, indent=1) + "\n")
    print(f"wrote {args.out_bin} ({len(blob)} bytes, sha256 {stats['sha256'][:12]}), {args.out_json.name}, "
          f"{args.out_meta.relative_to(HERE.parent)}, {args.fixture.relative_to(HERE)} ({len(cases)} cases); {meta['seconds']} s")
    return 0


if __name__ == "__main__":
    sys.exit(main())
