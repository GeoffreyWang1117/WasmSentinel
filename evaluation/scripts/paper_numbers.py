#!/usr/bin/env python3
"""Generate LaTeX macros for every number the paper cites, straight from the
result JSONs under evaluation/results/2026-11. Missing experiments produce
macros that render as \\textbf{??} so a stale draft is visible, never wrong.

  python3 evaluation/scripts/paper_numbers.py --out paper-asiaccs/tables/numbers.tex
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]


def load(path):
    try:
        return json.loads(path.read_text())
    except (OSError, json.JSONDecodeError):
        return None


class Macros:
    def __init__(self):
        self.lines = []

    def add(self, name, value, fmt="{}"):
        if value is None:
            body = r"\textbf{??}"
        else:
            body = fmt.format(value)
        # macro names may only contain letters
        assert name.isalpha(), name
        self.lines.append(f"\\newcommand{{\\{name}}}{{{body}}}")

    def text(self, header):
        return header + "\n".join(self.lines) + "\n"


FAMILY_SUFFIX = {"Adduser": "Adduser", "Hydra_FTP": "HydraFtp", "Hydra_SSH": "HydraSsh",
                 "Java_Meterpreter": "JavaMeterpreter", "Meterpreter": "Meterpreter", "Web_Shell": "WebShell"}
MODEL_LABEL = {
    "wasmsentinel_rf": r"\sys RF (Wasm, v1 features)",
    "wasmsentinel_mlp": r"\sys MLP (Wasm, v1 features)",
    "rf": "Random Forest (scikit-learn), supervised, v1 features",
    "lstm": "LSTM on raw sequence, supervised",
    "stide": "STIDE 6-gram, normal only",
    "iforest": "Isolation Forest, normal only, v1 features",
}
MODEL_SUFFIX = {"wasmsentinel_rf": "RfWasm", "wasmsentinel_mlp": "Mlp", "rf": "Rf", "lstm": "Lstm", "stide": "Stide", "iforest": "IForest"}
GEN = "% Generated by evaluation/scripts/paper_numbers.py; do not edit.\n\\setlength{\\tabcolsep}{3.5pt}\n"


def e2_prov(R):
    return load(R / "e2/e2_results.json")


def tex(s):
    return str(s).replace("_", r"\_").replace("%", r"\%")


def write_tables(tables_dir, e1, e2, iso, e3=None, e4=None, e5=None):
    """Table bodies straight from the JSONs, one file per table."""
    tables_dir.mkdir(parents=True, exist_ok=True)
    # E1 main table; the paired column is against the forest in Wasm when that
    # arm exists (results from 2026-10-25 on), else against the MLP in Wasm.
    ref_key, ref_paired = "wasmsentinel_mlp", "paired_vs_wasmsentinel_auprc"
    if e1 and e1.get("paired_vs_wasmsentinel_rf_auprc"):
        ref_key, ref_paired = "wasmsentinel_rf", "paired_vs_wasmsentinel_rf_auprc"
    rows = [r"\begin{tabular}{@{}lrrrrrl@{}}", r"\toprule",
            r"Model & AUPRC & AUROC & R@5\% & R@1\% & F1@5\% & $\Delta$AUPRC [95\% CI] \\", r"\midrule"]
    if e1:
        for key, label in MODEL_LABEL.items():
            s = e1["summary"].get(key)
            if not s:
                continue
            pz = e1[ref_paired].get(key)
            if key == ref_key:
                delta = "---"
            elif pz["auprc_diff_mean"] == 0 and tuple(pz["ci95"]) == (0, 0):
                delta = "0 (identical scores)"  # the forest in Wasm vs the scikit-learn forest it was exported from
            else:
                delta = "{:+.3f} [{:+.3f}, {:+.3f}]".format(pz["auprc_diff_mean"], *pz["ci95"])
            rows.append("{} & {:.3f} $\\pm$ {:.3f} & {:.3f} & {:.3f} & {:.3f} & {:.3f} & {} \\\\".format(
                label, s["auprc"]["mean"], s["auprc"]["std"], s["roc_auc"]["mean"], s["recall_at_fpr5"]["mean"],
                s["recall_at_fpr1"]["mean"], s["op_fpr5_f1"]["mean"], delta))
    else:
        rows.append(r"\multicolumn{7}{c}{\textbf{?? E1 results missing}} \\")
    rows += [r"\bottomrule", r"\end{tabular}"]
    (tables_dir / "e1_table.tex").write_text(GEN + "\n".join(rows) + "\n")
    # E1 per-family table
    fams = list(FAMILY_SUFFIX)
    short_fam = {"Adduser": "Adduser", "Hydra_FTP": "Hydra-FTP", "Hydra_SSH": "Hydra-SSH", "Java_Meterpreter": "Java-Met.", "Meterpreter": "Meterp.", "Web_Shell": "Web-Shell"}
    rows = [r"\begin{tabular}{@{}l" + "r" * len(fams) + "@{}}", r"\toprule",
            "Model & " + " & ".join(short_fam.get(f, tex(f)) for f in fams) + r" \\", r"\midrule"]
    if e1:
        for key, label in MODEL_LABEL.items():
            fam = e1["summary"].get(key, {}).get("per_family_recall_at_fpr5")
            if not fam:
                continue
            short = label.split(",")[0].split(" (")[0]
            rows.append(short + " & " + " & ".join("{:.2f}".format(fam.get(f, float("nan"))) for f in fams) + r" \\")
    rows += [r"\bottomrule", r"\end{tabular}"]
    (tables_dir / "e1_family_table.tex").write_text(GEN + "\n".join(rows) + "\n")
    # E2 cost table
    rows = [r"\begin{tabular}{@{}llr@{}}", r"\toprule", r"Measurement & Unit of work & Median \\", r"\midrule"]
    if e2 and e2.get("timing"):
        t = e2["timing"]; gb = t.get("go_engine_ns_per_call", {})
        us = lambda ns: "{:.1f}".format(ns / 1000) + r"~\si{\micro\second}"
        rows += [
            r"Host engine, empty guest & one call & " + us(gb["BenchmarkInvokeEcho"]) + r" \\",
            r"\texttt{ml\_detector}, JSON event & one process event & " + us(gb["BenchmarkRealMLDetectorJSON"]) + r" \\",
            r"\texttt{ml\_detector}, binary event & one process event & " + us(gb["BenchmarkRealMLDetectorRaw"]) + r" \\",
            r"\midrule",
            "Native Rust, MLP & one trace ({} syscalls) & ".format(t["trace_len_median"]) + us(t["ns_per_call_median"]["native_rust"]) + r" \\",
            r"Wasm via wasmtime-py (+Python call), MLP & one trace & " + us(t["ns_per_call_median"]["wasm_wasmtime_py"]) + r" \\",
            r"NumPy reference, MLP & one trace & " + us(t["ns_per_call_median"]["numpy"]) + r" \\",
        ]
        if "native_rust_rf" in t["ns_per_call_median"]:
            rows += [
                r"Native Rust, forest & one trace & " + us(t["ns_per_call_median"]["native_rust_rf"]) + r" \\",
                r"Wasm via wasmtime-py (+Python call), forest & one trace & " + us(t["ns_per_call_median"]["wasm_rf_wasmtime_py"]) + r" \\",
            ]
    else:
        rows.append(r"\multicolumn{3}{c}{\textbf{?? E2 results missing}} \\")
    rows += [r"\bottomrule", r"\end{tabular}"]
    (tables_dir / "e2_table.tex").write_text(GEN + "\n".join(rows) + "\n")
    # E6 isolation table
    rows = [r"\begin{tabular}{@{}lp{6.2cm}llrr@{}}", r"\toprule",
            r"Module & Attempt & Expected & Outcome & ms & MiB \\", r"\midrule"]
    if iso:
        for c in iso["cases"]:
            rows.append(r"\texttt{" + tex(c["module"]) + "} & " + tex(c["attempt"]) + " & " + r"\texttt{" + tex(c["expect"]) + "} & " +
                        tex(c["outcome"]) + (" " if c["contained"] else r" \textbf{(escaped)} ") + "& {:.2f} & {:.1f}".format(c["elapsed_ms"], c["memory_mib_after"]) + r" \\")
    else:
        rows.append(r"\multicolumn{6}{c}{\textbf{?? isolation results missing}} \\")
    rows += [r"\bottomrule", r"\end{tabular}"]
    (tables_dir / "isolation_table.tex").write_text(GEN + "\n".join(rows) + "\n")
    # E3 table (Model = ml_detector's deep path: the MLP default or the forest)
    rows = [r"\begin{tabular}{@{}llrrrrrrr@{}}", r"\toprule",
            r"Encoding & Model & Offered & Achieved & p50 & p99 & p99.9 & Detect p50 & RSS \\",
            r" & & ev/s & ev/s & \si{\micro\second} & \si{\micro\second} & \si{\micro\second} & \si{\micro\second} & MiB \\", r"\midrule"]
    if e3:
        def e3_key(cell):
            enc, eps, model = (cell.split("@") + ["mlp"])[:3]
            return int(eps), enc != "json", model != "mlp"
        order = sorted(e3["summary"].items(), key=lambda kv: e3_key(kv[0]))
        last = None
        for cell, v in order:
            enc, eps, model = (cell.split("@") + ["mlp"])[:3]
            if last is not None and eps != last:
                rows.append(r"\addlinespace")
            last = eps
            e = v["e2e_us"]
            rows.append("{} & {} & {:,} & {:,.0f} & {:,.0f} & {:,.0f} & {:,.0f} & {:,.0f} & {:.0f} \\\\".format(
                enc, model.upper(), int(eps), v["achieved_eps"]["mean"], e["p50"]["mean"], e["p99"]["mean"], e["p999"]["mean"],
                v["detect_us"]["p50"]["mean"], v["max_rss_kb"]["mean"] / 1024))
    else:
        rows.append(r"\multicolumn{9}{c}{\textbf{?? E3 results missing}} \\")
    rows += [r"\bottomrule", r"\end{tabular}"]
    (tables_dir / "e3_table.tex").write_text(GEN + "\n".join(rows) + "\n")
    # E4 table
    WL = {"nginx": ("nginx", "req/s"), "redis": ("redis", "ops/s"), "postgres": ("PostgreSQL", "tps")}
    ARM = {"none": "none", "wasmsentinel": r"\sys", "falco": "Falco", "tetragon": "Tetragon"}
    rows = [r"\begin{tabular}{@{}llrrrr@{}}", r"\toprule",
            r"Workload & Monitor & Throughput & $\Delta$ [95\% CI] & CPU \% & RSS MiB \\", r"\midrule"]
    if e4:
        first = True
        for wl, arms in e4["summary"].items():
            if not first:
                rows.append(r"\addlinespace")
            first = False
            name, unit = WL.get(wl, (wl, ""))
            for arm, c in arms.items():
                delta = "---" if arm == "none" else "{:+.1f} [{:+.1f}, {:+.1f}]".format(c["throughput_delta_pct_mean"], *c["throughput_delta_pct_ci95"])
                cpu = "---" if arm == "none" else "{:.1f}".format(c["monitor_cpu_pct_mean"])
                rss = "---" if arm == "none" else "{:.0f}".format(c["monitor_rss_mib_max"])
                rows.append("{} & {} & {:,.0f} {} & {} & {} & {} \\\\".format(name if arm == "none" else "", ARM.get(arm, arm), c["throughput_mean"], unit, delta, cpu, rss))
    else:
        rows.append(r"\multicolumn{6}{c}{\textbf{?? E4 results missing}} \\")
    rows += [r"\bottomrule", r"\end{tabular}"]
    (tables_dir / "e4_table.tex").write_text(GEN + "\n".join(rows) + "\n")
    # E5 table
    SC = {"shadow": r"read \texttt{/etc/shadow}", "tmpexec": r"exec from \texttt{/tmp}", "connect": "connect :4444"}
    rows = [r"\begin{tabular}{@{}llrrrrr@{}}", r"\toprule",
            r"System & Detection & Detected & Med.\ ms & p90 ms & RSS MiB & CPU \% \\", r"\midrule"]
    if e5:
        trials = int(e5["provenance"]["args"]["trials"])
        first = True
        for system, r in e5["results"].items():
            if not first:
                rows.append(r"\addlinespace")
            first = False
            res = r["resources"]
            foot = ("{:.0f}".format(res.get("rss_kb_max", 0) / 1024), "{:.1f}".format(res.get("cpu_pct_mean", 0)))
            for k, (sc, pdata) in enumerate(r["scenarios"].items()):
                lat = pdata.get("latency_ms") or {}
                rows.append("{} & {} & {}/{} & {} & {} & {} & {} \\\\".format(
                    ARM.get(system, system) if k == 0 else "", SC.get(sc, sc), pdata["detected"], pdata.get("trials", trials),
                    "{:.1f}".format(lat["median"]) if lat else "---", "{:.1f}".format(lat["p90"]) if lat else "---",
                    foot[0] if k == 0 else "", foot[1] if k == 0 else ""))
    else:
        rows.append(r"\multicolumn{7}{c}{\textbf{?? E5 results missing}} \\")
    rows += [r"\bottomrule", r"\end{tabular}"]
    (tables_dir / "e5_table.tex").write_text(GEN + "\n".join(rows) + "\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", type=Path, default=REPO / "evaluation/results/2026-11")
    ap.add_argument("--out", type=Path, default=REPO / "paper-asiaccs/tables/numbers.tex")
    args = ap.parse_args()
    R = args.results
    m = Macros()
    commits = {}

    # ---- E6 isolation
    iso = load(R / "isolation/isolation.json")
    m.add("isoContained", iso and iso["contained"])
    m.add("isoTotal", iso and iso["total"])
    m.add("isoModules", iso and len({c["module"] for c in iso["cases"]}))
    m.add("isoMemoryCapMiB", iso and iso["limits"]["memory_bytes"] // (1 << 20))
    m.add("isoFuel", iso and iso["limits"]["fuel"], "{:,}")
    m.add("isoTimeout", iso and iso["limits"]["timeout"])

    # ---- parity (P1.4)
    par = (R / "parity/parity.txt")
    ptxt = par.read_text() if par.exists() else ""
    import re
    mm = re.search(r"inputs: (\d+)", ptxt)
    m.add("parityInputs", int(mm.group(1)) if mm else None, "{:,}")
    mm = re.search(r"max \|score diff\|\s*=\s*([\d.e+-]+)", ptxt)
    m.add("parityMaxScoreDiff", float(mm.group(1)) if mm else None, "{:.1e}")

    # ---- E1
    e1 = load(R / "e1/e1_results.json")
    prov = (e1 or e2_prov(R) or {}).get("provenance", {})
    m.add("provCpu", prov.get("cpu", "").replace(" 16-Core Processor", "") or None)
    m.add("provKernel", prov.get("kernel") or None)
    if e1:
        commits["e1"] = e1["provenance"]["git_commit"][:12]
        m.add("eOneNormal", e1["dataset"]["normal"], "{:,}")
        m.add("eOneAttack", e1["dataset"]["attack"])
        m.add("eOneFolds", e1["provenance"]["args"]["folds"])
        m.add("eOneSeeds", e1["provenance"]["args"]["seeds"])
        names = MODEL_SUFFIX
        for key, suf in names.items():
            s = e1["summary"].get(key)
            m.add(f"eOneAuprc{suf}", s and s["auprc"]["mean"], "{:.3f}")
            m.add(f"eOneAuprcStd{suf}", s and s["auprc"]["std"], "{:.3f}")
            m.add(f"eOneAuroc{suf}", s and s["roc_auc"]["mean"], "{:.3f}")
            m.add(f"eOneRecallFprFive{suf}", s and s["recall_at_fpr5"]["mean"], "{:.3f}")
            m.add(f"eOneRecallFprOne{suf}", s and s["recall_at_fpr1"]["mean"], "{:.3f}")
            m.add(f"eOneFOneOpFive{suf}", s and s["op_fpr5_f1"]["mean"], "{:.3f}")
        # eOneDiff*: AUPRC(MLP in Wasm) - AUPRC(model); eOneDiffVsRf*: AUPRC(RF in Wasm) - AUPRC(model)
        for key, suf in names.items():
            if key != "wasmsentinel_mlp":
                pz = e1["paired_vs_wasmsentinel_auprc"].get(key)
                m.add(f"eOneDiff{suf}", pz and pz["auprc_diff_mean"], "{:+.3f}")
                m.add(f"eOneDiffCiLo{suf}", pz and pz["ci95"][0], "{:+.3f}")
                m.add(f"eOneDiffCiHi{suf}", pz and pz["ci95"][1], "{:+.3f}")
            if key != "wasmsentinel_rf":
                pz = e1.get("paired_vs_wasmsentinel_rf_auprc", {}).get(key)
                m.add(f"eOneDiffVsRf{suf}", pz and pz["auprc_diff_mean"], "{:+.3f}")
                m.add(f"eOneDiffVsRfCiLo{suf}", pz and pz["ci95"][0], "{:+.3f}")
                m.add(f"eOneDiffVsRfCiHi{suf}", pz and pz["ci95"][1], "{:+.3f}")
        mlp_runs = [r for r in e1["runs"] if r["model"] == "wasmsentinel_mlp"]
        rf_runs = [r for r in e1["runs"] if r["model"] == "wasmsentinel_rf"]
        m.add("eOneWasmNumpyMaxDiff", max(r["info"].get("wasm_vs_numpy_max_abs_diff", 0) for r in mlp_runs) if mlp_runs else None, "{:.1e}")
        m.add("eOneWasmSklearnMaxDiff", max(r["info"].get("wasm_vs_sklearn_max_abs_diff", 0) for r in rf_runs) if rf_runs else None, "{:.1e}")
        m.add("eOneForestNodesMean", sum(r["info"]["n_nodes"] for r in rf_runs) / len(rf_runs) if rf_runs else None, "{:,.0f}")
        m.add("eOneForestKiBMean", sum(r["info"]["bytes"] for r in rf_runs) / len(rf_runs) / 1024 if rf_runs else None, "{:,.0f}")
        for key, suf in names.items():
            fam = e1["summary"].get(key, {}).get("per_family_recall_at_fpr5", {})
            for family, fsuf in FAMILY_SUFFIX.items():
                m.add(f"eOneFam{fsuf}{suf}", fam.get(family), "{:.2f}")
    else:
        for name in ("eOneNormal", "eOneAttack", "eOneAuprcMlp", "eOneAuprcRf", "eOneAuprcLstm", "eOneAuprcStide", "eOneAuprcIForest"):
            m.add(name, None)

    # ---- E2
    e2 = load(R / "e2/e2_results.json")
    if e2:
        commits["e2"] = e2["provenance"]["git_commit"][:12]
        c = e2["consistency"]
        m.add("eTwoTraces", c["traces"], "{:,}")
        m.add("eTwoMaxDiffNumpyWasm", c["max_abs_diff_numpy_vs_wasm"], "{:.1e}")
        m.add("eTwoMaxDiffNativeWasm", c["max_abs_diff_native_vs_wasm"], "{:.1e}")
        t = e2.get("timing")
        m.add("eTwoTraceLen", t and t["trace_len_median"])
        m.add("eTwoTracesTimed", t and t["traces_timed"])
        for k, suf in (("numpy", "Numpy"), ("native_rust", "Native"), ("wasm_wasmtime_py", "Wasm"),
                       ("native_rust_rf", "NativeRf"), ("wasm_rf_wasmtime_py", "WasmRf")):
            v = (t or {}).get("ns_per_call_median", {}).get(k)
            m.add(f"eTwoUsPerCall{suf}", v and v / 1000, "{:.1f}")
        rf = c.get("rf") or {}
        m.add("eTwoRfMaxDiffNumpyWasm", rf.get("max_abs_diff_numpy_vs_wasm"), "{:.1e}")
        m.add("eTwoRfMaxDiffNativeWasm", rf.get("max_abs_diff_native_vs_wasm"), "{:.1e}")
        gb = (t or {}).get("go_engine_ns_per_call", {})
        m.add("eTwoEngineOverheadUs", gb.get("BenchmarkInvokeEcho") and gb["BenchmarkInvokeEcho"] / 1000, "{:.1f}")
        m.add("eTwoMlJsonUs", gb.get("BenchmarkRealMLDetectorJSON") and gb["BenchmarkRealMLDetectorJSON"] / 1000, "{:.1f}")
        m.add("eTwoMlRawUs", gb.get("BenchmarkRealMLDetectorRaw") and gb["BenchmarkRealMLDetectorRaw"] / 1000, "{:.1f}")
    else:
        for name in ("eTwoTraces", "eTwoMaxDiffNumpyWasm", "eTwoUsPerCallWasm", "eTwoEngineOverheadUs"):
            m.add(name, None)

    # ---- the embedded forest (rules/ml-detector/train/rf_model.json) and the module size
    rfm = load(REPO / "rules/ml-detector/train/rf_model.json")
    m.add("rfTrees", rfm and rfm["n_trees"])
    m.add("rfNodes", rfm and rfm["n_nodes"], "{:,}")
    m.add("rfMaxDepth", rfm and rfm["max_depth"])
    m.add("rfKiB", rfm and rfm["bytes"] / 1024, "{:,.0f}")
    m.add("rfExporterMaxDiff", rfm and rfm["exporter_vs_sklearn_max_abs_diff"], "{:.1e}")
    wasm_path = REPO / "rules/wasm/ml_detector.wasm"
    m.add("mlModuleKiB", wasm_path.stat().st_size / 1024 if wasm_path.exists() else None, "{:,.0f}")

    # ---- E3
    e3 = load(R / "e3/e3_results.json")
    if e3:
        commits["e3"] = e3["provenance"]["git_commit"][:12]
        # One macro set per (encoding, rate, model) of the full grid, so a cell
        # the results lack still defines its macros (as "??"). ...Rf suffix:
        # ml_detector's deep path on the embedded forest ({"model":"rf"}); no
        # suffix: the MLP default.
        for enc in ("json", "binary"):
            for eps in (1000, 10000, 50000):
                for model in ("mlp", "rf"):
                    v = e3["summary"].get(f"{enc}@{eps}" if model == "mlp" else f"{enc}@{eps}@{model}")
                    suf = {"json": "Json", "binary": "Bin"}[enc] + {1000: "OneK", 10000: "TenK", 50000: "FiftyK"}[eps] + ("Rf" if model == "rf" else "")
                    m.add(f"eThreeAchieved{suf}", v and v["achieved_eps"]["mean"], "{:,.0f}")
                    m.add(f"eThreePFifty{suf}", v and v["e2e_us"]["p50"]["mean"], "{:,.0f}")
                    m.add(f"eThreePNinetyNine{suf}", v and v["e2e_us"]["p99"]["mean"], "{:,.0f}")
                    m.add(f"eThreePNineNineNine{suf}", v and v["e2e_us"]["p999"]["mean"], "{:,.0f}")
                    m.add(f"eThreeRssMiB{suf}", v and v["max_rss_kb"]["mean"] / 1024, "{:.0f}")
                    m.add(f"eThreeDetectPFifty{suf}", v and v["detect_us"]["p50"]["mean"], "{:,.0f}")
                    m.add(f"eThreeDetectPNinetyNine{suf}", v and v["detect_us"]["p99"]["mean"], "{:,.0f}")
        sat = {enc: v for enc, v in ((c.split("@")[0], v) for c, v in e3["summary"].items() if c.endswith("@50000"))}
        if "json" in sat and "binary" in sat:
            m.add("eThreeBinGainPct", 100 * (sat["binary"]["achieved_eps"]["mean"] / sat["json"]["achieved_eps"]["mean"] - 1), "{:.0f}")
    else:
        m.add("eThreeAchievedBinTenK", None)

    # ---- E4
    e4 = load(R / "e4/e4_results.json")
    if e4:
        commits["e4"] = e4["provenance"]["git_commit"][:12]
        wl_suf = {"nginx": "Nginx", "redis": "Redis", "postgres": "Pg"}
        arm_suf = {"none": "None", "wasmsentinel": "Ws", "falco": "Falco", "tetragon": "Tetragon"}
        for wl, arms in e4["summary"].items():
            for arm, c in arms.items():
                suf = wl_suf.get(wl, wl.title()) + arm_suf.get(arm, arm.title())
                m.add(f"eFourTput{suf}", c["throughput_mean"], "{:,.0f}")
                if arm != "none":
                    m.add(f"eFourDelta{suf}", c.get("throughput_delta_pct_mean"), "{:+.1f}")
                    m.add(f"eFourDeltaCiLo{suf}", c["throughput_delta_pct_ci95"][0], "{:+.1f}")
                    m.add(f"eFourDeltaCiHi{suf}", c["throughput_delta_pct_ci95"][1], "{:+.1f}")
                m.add(f"eFourCpu{suf}", c["monitor_cpu_pct_mean"], "{:.1f}")
                m.add(f"eFourRss{suf}", c["monitor_rss_mib_max"], "{:.0f}")
    else:
        m.add("eFourDeltaNginxWs", None)

    # ---- E5
    e5 = load(R / "e5/e5_results.json")
    if e5:
        commits["e5"] = e5["provenance"]["git_commit"][:12]
        sys_suf = {"wasmsentinel": "Ws", "falco": "Falco", "tetragon": "Tetragon"}
        sc_suf = {"shadow": "Shadow", "tmpexec": "TmpExec", "connect": "Connect"}
        m.add("eFiveTrials", e5["provenance"]["args"]["trials"])
        for system, r in e5["results"].items():
            for sc, p in r["scenarios"].items():
                suf = sys_suf[system] + sc_suf[sc]
                m.add(f"eFiveDetected{suf}", p["detected"])
                m.add(f"eFiveLatency{suf}", p["latency_ms"] and p["latency_ms"]["median"], "{:.1f}")
            m.add(f"eFiveRss{sys_suf[system]}", r["resources"].get("rss_kb_max", 0) / 1024, "{:.0f}")
            m.add(f"eFiveCpu{sys_suf[system]}", r["resources"].get("cpu_pct_mean"), "{:.1f}")
    else:
        m.add("eFiveDetectedWsShadow", None)

    write_tables(args.out.parent, e1, e2, iso, e3, e4, e5)

    header = "% Generated by evaluation/scripts/paper_numbers.py from " + str(R.relative_to(REPO)) + "\n% commits: " + ", ".join(f"{k}={v}" for k, v in sorted(commits.items())) + "\n% Do not edit; run `make numbers` in paper-asiaccs/.\n"
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(m.text(header))
